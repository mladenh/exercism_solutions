export const decodedValue = (color) => {
  let decoded = String(COLORS.indexOf(color[0])) + String(COLORS.indexOf(color[1]));
  return Number(decoded);
};

export const COLORS = [
  "black",
  "brown",
  "red",
  "orange",
  "yellow",
  "green",
  "blue",
  "violet",
  "grey",
  "white",
];